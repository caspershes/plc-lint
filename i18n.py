#!/usr/bin/env python3
"""
Лёгкий i18n без внешних зависимостей: словарь-каталог + t().

Язык выбирается так (см. resolve_locale): cookie `lang` > домен (.com → en) > DEFAULT_LANG.
В шаблонах строка берётся через глобал t('ключ'), контентные коллекции (тексты правил,
гайды, матрица тарифов) — через аксессоры rule_help(lang)/rule_fix(lang)/... .

Правило: t() возвращает обычную str (Jinja экранирует). Ключи с HTML-разметкой (суффикс
для наглядности не обязателен) рендерятся в шаблоне через |safe и НЕ подставляют
пользовательских данных. Пользовательские данные (имя файла и т.п.) идут только в
экранируемые строки.
"""

DEFAULT_LANG = "ru"
LANGS = ("ru", "en")


def resolve_locale(host, cookie):
    """cookie `lang` > домен (.com → en, .ru → ru) > DEFAULT_LANG."""
    if cookie in LANGS:
        return cookie
    if host:
        h = host.split(":")[0].lower()
        if h.endswith(".com"):
            return "en"
        if h.endswith(".ru"):
            return "ru"
    return DEFAULT_LANG


def t(key, lang, **kw):
    """Строка по ключу для языка lang; fallback на DEFAULT_LANG, затем на сам ключ."""
    s = STRINGS.get(lang, {}).get(key)
    if s is None:
        s = STRINGS[DEFAULT_LANG].get(key, key)
    if kw:
        try:
            s = s.format(**kw)
        except (KeyError, IndexError, ValueError):
            pass
    return s


# аксессоры контентных коллекций
def rule_help(lang):
    return RULE_HELP.get(lang, RULE_HELP[DEFAULT_LANG])


def rule_fix(lang):
    return RULE_FIX.get(lang, RULE_FIX[DEFAULT_LANG])


def severity_label(lang):
    return SEVERITY_LABEL.get(lang, SEVERITY_LABEL[DEFAULT_LANG])


def export_guides(lang):
    return EXPORT_GUIDES.get(lang, EXPORT_GUIDES[DEFAULT_LANG])


def plan_features(lang):
    return PLAN_FEATURES.get(lang, PLAN_FEATURES[DEFAULT_LANG])


def plan_desc(lang):
    return PLAN_DESC.get(lang, PLAN_DESC[DEFAULT_LANG])


def index_checks(lang):
    """Витрина «Что проверяем» — ГРУППЫ правил из движка, а не рукописный список.

    Раньше здесь лежали 18 карточек, набранных руками; движок тем временем дорос до 34
    правил, и витрина молча отстала — посетитель не видел ни контроля implicit-checks,
    ни четырёх последних правил. Теперь единственный источник — engine.RULES, а тексты
    берутся из RULE_TITLE/RULE_SHORT; правило без описания роняет tests/rules_coverage.py.

    Возвращает [(severity, подпись группы, [(заголовок, описание), ...]), ...].
    """
    import engine  # локальный импорт: i18n не должен зависеть от движка на уровне модуля

    titles, shorts = RULE_TITLE.get(lang, RULE_TITLE[DEFAULT_LANG]), rule_short(lang)
    groups = []
    for sev in ("high", "medium", "low"):
        rules = sorted((r for r, (s, _) in engine.RULES.items() if s == sev),
                       key=lambda r: titles.get(r, r))
        items = [(titles.get(r, r), shorts.get(r, "")) for r in rules]
        groups.append((sev, t(f"index.sev_{sev}", lang, n=len(items)), items))
    return groups


